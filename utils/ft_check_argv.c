int	ft_check_argv(char *s)
{
	size_t	i;

	i = 0;
	while (s[i])
	{
		while (s[i] == 32)
			i++;
		if (!s[i])
			break ;
		if (s[i] == '-' || s[i] == '+')
			i++;
		if (!(s[i] >= '0' && s[i] <= '9'))
			return (0);
		while (s[i] >= '0' && s[i] <= '9')
			i++;
		if (s[i] != 32 && s[i] != '\0')
			return (0);
	}
	return (1);
}