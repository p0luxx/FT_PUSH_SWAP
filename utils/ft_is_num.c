#include "push_swap.h"

int	ft_is_num(char	*str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		if ((str[i] >= '0' && str[i] <= '9') || str[i] == 32)
			return (0);
		i++;
	}
	return (1);
}
