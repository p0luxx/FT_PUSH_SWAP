int	ft_len_nb(int n)
{
	int	len;

	len = 1;
	if (n == -2147483648)
	{
		return (11);
	}
	if (n < 0)
	{
		len++;
		n = -n;
	}
	while (n > 9)
	{
		len++;
		n = n / 10;
	}
	return (len);
}
